import fs from "node:fs";
import path from "node:path";

const DEFAULT_SKIP_DIRS = new Set([".git", "node_modules", ".next", ".venv", "venv", "__pycache__"]);

const BLACKHOLE_PATTERNS = [
  { id: "lockfile", label: "Lockfiles", re: /(?:^|[\\/])(package-lock\.json|pnpm-lock\.yaml|yarn\.lock|poetry\.lock|Cargo\.lock|uv\.lock)$/i, ignoreRule: "package-lock.json\npnpm-lock.yaml\nyarn.lock\nCargo.lock\nuv.lock" },
  { id: "bundle", label: "Minified / Bundled Assets", re: /\.(min\.js|min\.css|map|bundle\.js)$/i, ignoreRule: "*.min.js\n*.min.css\n*.map" },
  { id: "dist", label: "Build / Dist Outputs", re: /(?:^|[\\/])(dist|build|coverage|out|\.turbo)[\\/]/i, ignoreRule: "dist/\nbuild/\ncoverage/" },
  { id: "data_dump", label: "Large Data / Log Dumps", re: /\.(csv|tsv|log|sql|sqlite|jsonl)$/i, ignoreRule: "*.log\n*.csv\n*.jsonl\n*.sqlite" },
  { id: "binary_or_archive", label: "Archives / Media", re: /\.(zip|tar|gz|png|jpg|jpeg|webp|pdf|ofd|mp4|woff2?)$/i, ignoreRule: "*.zip\n*.pdf\n*.png\n*.jpg" },
];

export function estimateTokens(text) {
  if (!text) return 0;
  let cjk = 0;
  for (let i = 0; i < text.length; i++) {
    if (text.charCodeAt(i) > 0x2e80) cjk++;
  }
  const ascii = text.length - cjk;
  return Math.ceil(ascii / 4 + cjk * 1.15);
}

export function classifyBlackhole(relPath, bytes, tokens) {
  for (const bp of BLACKHOLE_PATTERNS) {
    if (bp.re.test(relPath)) return { isBlackhole: true, category: bp.label, ignoreHint: bp.ignoreRule };
  }
  if (tokens >= 8000 || bytes >= 32768) {
    return { isBlackhole: true, category: "Oversized Context File (>=8k tok)", ignoreHint: relPath.replace(/\\/g, "/") };
  }
  return { isBlackhole: false, category: "Source", ignoreHint: "" };
}

export function scanRepository(targetDir) {
  const root = path.resolve(targetDir);
  const files = [];
  const dirTokens = new Map();
  const categoryStats = new Map();
  const suggestedRules = new Set(["node_modules/", ".git/", "dist/", "build/", "*.log"]);

  function walk(cur) {
    let entries;
    try {
      entries = fs.readdirSync(cur, { withFileTypes: true });
    } catch {
      return;
    }
    for (const ent of entries) {
      const full = path.join(cur, ent.name);
      if (ent.isDirectory()) {
        if (DEFAULT_SKIP_DIRS.has(ent.name)) continue;
        walk(full);
        continue;
      }
      if (!ent.isFile()) continue;
      const rel = path.relative(root, full).replace(/\\/g, "/");
      let stat;
      try {
        stat = fs.statSync(full);
      } catch {
        continue;
      }
      let tokens = Math.ceil(stat.size / 4);
      const ext = path.extname(ent.name).toLowerCase();
      const textExts = new Set([".js", ".mjs", ".ts", ".tsx", ".jsx", ".py", ".md", ".json", ".yaml", ".yml", ".html", ".css", ".txt", ".xml", ".csv", ".sql", ".sh"]);
      if (textExts.has(ext) && stat.size <= 512 * 1024) {
        try {
          tokens = estimateTokens(fs.readFileSync(full, "utf-8"));
        } catch {
          tokens = Math.ceil(stat.size / 4);
        }
      }
      const cls = classifyBlackhole(rel, stat.size, tokens);
      if (cls.isBlackhole && cls.ignoreHint) {
        cls.ignoreHint.split("\n").forEach(r => suggestedRules.add(r));
      }
      const topDir = rel.includes("/") ? rel.split("/")[0] : "(root)";
      dirTokens.set(topDir, (dirTokens.get(topDir) || 0) + tokens);
      categoryStats.set(cls.category, (categoryStats.get(cls.category) || 0) + tokens);
      files.push({
        path: rel,
        bytes: stat.size,
        tokens,
        isBlackhole: cls.isBlackhole,
        category: cls.category,
      });
    }
  }

  walk(root);
  files.sort((a, b) => b.tokens - a.tokens);

  const totalTokens = files.reduce((s, f) => s + f.tokens, 0);
  const blackholeTokens = files.filter(f => f.isBlackhole).reduce((s, f) => s + f.tokens, 0);
  const savingsPct = totalTokens > 0 ? Number(((blackholeTokens / totalTokens) * 100).toFixed(1)) : 0;

  return {
    root,
    fileCount: files.length,
    totalTokens,
    blackholeTokens,
    leanTokens: Math.max(0, totalTokens - blackholeTokens),
    savingsPct,
    topOffenders: files.slice(0, 15),
    byDirectory: [...dirTokens.entries()].sort((a, b) => b[1] - a[1]).slice(0, 10).map(([dir, tokens]) => ({ dir, tokens })),
    byCategory: [...categoryStats.entries()].sort((a, b) => b[1] - a[1]).map(([category, tokens]) => ({ category, tokens })),
    ignoreContent: [
      "# Generated by context-diet (https://github.com/qingzhou1204/context-diet)",
      ...Array.from(suggestedRules),
      "",
    ].join("\n"),
  };
}
